-- 1) DESAJUSTES: impresora guardada bajo una empresa distinta a la del CSV.
--    (RFM8Z00955 debe salir aquí: BD=Geprecon vs CSV=Tecnicas de Control)
SELECT c.serial, c.grupo_csv, e.nombre_oficial AS empresa_bd_actual, i.empresa_id
FROM csv_grupos c
JOIN impresoras i ON i.serial_number = c.serial
LEFT JOIN empresas e ON e.id = i.empresa_id
WHERE NOT (e.nombre_oficial <=> c.grupo_csv)
ORDER BY c.grupo_csv, c.serial;

-- 2) SERIES DEL CSV QUE NO EXISTEN EN impresoras (se saltan al facturar).
SELECT c.serial, c.grupo_csv
FROM csv_grupos c
LEFT JOIN impresoras i ON i.serial_number = c.serial
WHERE i.serial_number IS NULL
ORDER BY c.grupo_csv, c.serial;

